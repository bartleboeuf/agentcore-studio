class I18n {
  constructor(lang = "en") {
    this.lang = TRANSLATIONS[lang] ? lang : "en";
  }

  t(key, vars = {}) {
    let text = (TRANSLATIONS[this.lang] && TRANSLATIONS[this.lang][key]) || (TRANSLATIONS["en"] && TRANSLATIONS["en"][key]) || key;
    Object.entries(vars).forEach(([k, v]) => {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
    });
    return text;
  }

  setLang(lang) {
    if (TRANSLATIONS[lang]) {
      this.lang = lang;
    }
  }

  getLang() {
    return this.lang;
  }

  getSupportedLangs() {
    return Object.keys(TRANSLATIONS);
  }
}

// Priority: server env var (injected as window.STUDIO_LANG) → user localStorage → browser locale → "en"
const _initLang = (typeof window !== "undefined" && window.STUDIO_LANG && TRANSLATIONS[window.STUDIO_LANG] ? window.STUDIO_LANG : null) ||
  localStorage.getItem("studio_language") ||
  navigator.language.split("-")[0] ||
  "en";

const i18n = new I18n(_initLang);

function t(key, vars = {}) {
  return i18n.t(key, vars);
}

if (typeof module !== "undefined" && module.exports) {
  module.exports = { I18n, i18n, t };
}
